/**
 * 卡片主键 —— 全项目唯一入口
 * ---------------------------------------------------------------------------
 * 只回答一个问题：一条数据的**稳定 key** 是什么。用途：
 *   · v-for 的 :key（同名作品不会串 DOM —— 早先拿 title 当 key 的隐患）
 *   · 以后做「按 id 排序 / 去重 / 记住选中态」时的取键处
 *
 * 为什么用我们自己的主键，而不是来源 id（bgmid / mikanid）：
 *   1. 来源 id 只说明「这条数据从哪抓的」，不是作品身份 —— 同一作品两路数据都能
 *      抓到时会变成两个 key；
 *   2. 主键由后端给（数据库主键），同一作品在库里只有一条记录，换源也不变；
 *   3. 后续内容不止番剧（剧场版 / OVA / 其他媒体），主键天然通用。
 * 将来接口字段改名（如 id → contentId），只改这里一处。
 */

/** 取卡片主键；拿不到主键返回 '' */
export function orderKeyOf(item) {
  if (item == null) return ''
  const id = item.id
  return id == null ? '' : String(id)
}

